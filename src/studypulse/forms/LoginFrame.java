    public LoginFrame(String email) {
        this();
        txtEmail.setText(email);
        txtPassword.requestFocusInWindow();
    }

    private void applyColors() {
        getContentPane().setBackground(BACKGROUND);
        lblLogo.setForeground(ACCENT);
        btnLogin.setBackground(ACCENT);
        btnLogin.setForeground(Color.WHITE);
        btnLogin.setFocusPainted(false);
        styleLink(btnCreateAccount, ACCENT);
        styleLink(btnLoadDemo, TEXT_MUTED);
        lblError.setText(" ");
        chkShowPassword.setOpaque(false);
        passwordEchoChar = txtPassword.getEchoChar();
    }

    static void styleLink(JButton button, Color color) {
        button.setForeground(color);
        button.setContentAreaFilled(false);
        button.setBorderPainted(false);
        button.setFocusPainted(false);
        button.setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
    }

    private void login() {
        lblError.setText(" ");
        String email = txtEmail.getText().trim();
        char[] password = txtPassword.getPassword();
        try {
            if (email.isEmpty() || password.length == 0) {
                lblError.setText("Enter your email and password.");
            } else if (!email.contains("@")) {
                lblError.setText("Enter a valid email address.");
            } else {
                Main.userEmail = email;
                if (DEMO_EMAIL.equals(email)) {
                    Main.userName = "Demo Student";
                } else if (Main.userName.equals("Student")) {
                    Main.userName = email.substring(0, email.indexOf('@'));
                }
                new DashboardFrame().setVisible(true);
                ToastFrame.showToast("Welcome back", "Logged in as " + email, ACCENT);
                dispose();
                return;
            }
            txtPassword.setText("");
            txtPassword.requestFocusInWindow();
        } finally {
            Arrays.fill(password, '\0');
        }
    }

    /** Fills in the demo account. */
    private void loadDemoData() {
        txtEmail.setText(DEMO_EMAIL);
        txtPassword.setText(DEMO_PASSWORD);
        JOptionPane.showMessageDialog(this, "Demo account filled in.\n\nLog in with "
                + DEMO_EMAIL + " / " + DEMO_PASSWORD + ".", "Demo data", JOptionPane.INFORMATION_MESSAGE);
    }

    private void togglePasswordVisible() {
        txtPassword.setEchoChar(chkShowPassword.isSelected() ? (char) 0 : passwordEchoChar);
    }

    private void openSignup() {
        new SignupFrame().setVisible(true);
        dispose();
    }

