    private void signup() {
        lblError.setText(" ");
        String name = txtFullName.getText().trim();
        String email = txtEmail.getText().trim();
        char[] password = txtPassword.getPassword();
        char[] confirm = txtConfirmPassword.getPassword();
        try {
            if (name.isEmpty() || email.isEmpty()) {
                lblError.setText("Enter your full name and email.");
            } else if (!email.contains("@")) {
                lblError.setText("Enter a valid email address.");
            } else if (password.length < MIN_PASSWORD_LENGTH) {
                lblError.setText("Password must have at least " + MIN_PASSWORD_LENGTH + " characters.");
            } else if (!Arrays.equals(password, confirm)) {
                lblError.setText("The passwords do not match.");
            } else {
                Main.userName = name;
                Main.userEmail = email;
                JOptionPane.showMessageDialog(this, "Account created. Welcome to StudyPulse, " + name + "!",
                        "StudyPulse", JOptionPane.INFORMATION_MESSAGE);
                new DashboardFrame().setVisible(true);
                dispose();
            }
        } finally {
            Arrays.fill(password, '\0');
            Arrays.fill(confirm, '\0');
        }
    }

    private void backToLogin() {
        new LoginFrame(txtEmail.getText().trim()).setVisible(true);
        dispose();
    }

